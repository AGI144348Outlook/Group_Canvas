"""Fictional classroom QA only. No private exports or external models."""
import json,pathlib
from playwright.sync_api import sync_playwright,expect
ROOT=pathlib.Path(__file__).parent;QA=ROOT/'qa';QA.mkdir(exist_ok=True)
checks=[]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,device_scale_factor=1,accept_downloads=True)
    page=context.new_page();errors=[];page.on('pageerror',lambda _:errors.append('runtime error'))
    page.goto('https://group-canvas-echo-classroom.agi144348.workers.dev/',wait_until='networkidle')
    expect(page.locator('body')).to_have_attribute('data-ready','true')
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    expect(page.locator('.desk')).to_have_count(2)
    checks.append('phone layout, indexboard and two desks')
    page.screenshot(path=str(QA/'classroom-phone.png'),full_page=True)
    page.locator('#attempt').tap()
    expect(page.locator('#phase')).to_have_text('Your turn')
    expect(page.locator('#seen-stamp')).to_have_text('ע COPIED')
    expect(page.locator('#board-receipt')).to_have_text('COPY RECEIPT VERIFIED')
    expect(page.locator('#grade')).to_be_disabled()
    checks.append('learner attempt freezes before teacher feedback')
    page.reload(wait_until='networkidle')
    expect(page.locator('#phase')).to_have_text('Your turn')
    page.locator('#answer-choices button',has_text='Echo').tap()
    page.locator('#grade').tap()
    expect(page.locator('#scale-state')).to_have_text('<')
    expect(page.locator('#trial-count')).to_have_text('1 graded turns')
    checks.append('pending turn restored; teacher correction changes evidence')
    page.locator('#next').tap()
    page.locator('#attempt').tap()
    expect(page.locator('#echo-output')).not_to_have_text('A blank card, ready for an encounter.')
    page.locator('#answer-choices button',has_text='Timothy').tap()
    page.locator('#grade').tap()
    with page.expect_download() as download:page.locator('#export').tap()
    saved=QA/'export-temporary.json';download.value.save_as(str(saved))
    session=json.loads(saved.read_text());saved.unlink()
    assert session['learner']['completed']==2
    checks.append('second teacher turn and session export')
    page.locator('#evidence-tab').tap()
    expect(page.locator('#result-cards .result')).to_have_count(2)
    expect(page.locator('#result-cards')).to_contain_text('8/8')
    page.locator('#replay-next').tap()
    expect(page.locator('#replay-card')).to_contain_text('2 / 96')
    checks.append('actual Python evidence and distinct step-through replay')
    page.locator('#live-tab').tap()
    page.locator('#reset').tap()
    expect(page.locator('#trial-count')).to_have_text('2 graded turns')
    page.locator('#confirm-reset').tap()
    expect(page.locator('#trial-count')).to_have_text('0 graded turns')
    expect(page.locator('.word-card.yellow')).to_have_count(0)
    page.locator('#auto').tap()
    expect(page.locator('#trial-count')).to_have_text('8 graded turns',timeout=45000)
    expect(page.locator('#auto')).to_have_text('Watch guided turns')
    page.locator('#check').tap()
    expect(page.locator('#assessment')).to_contain_text('8 / 8')
    expect(page.locator('#assessment')).to_contain_text('Words remain yellow')
    checks.append('confirmed reset, live guided learning, frozen check, no automatic green admission')
    assert not errors
    checks.append('no browser runtime errors')
    browser.close()
(QA/'results.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'viewport':'390x844 touch'},indent=2))
print(str(len(checks))+' phone-browser checks passed.')
