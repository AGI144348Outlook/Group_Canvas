"""Read-only UI checks; never instantiate a learner or execute a teaching trial."""
import json,pathlib
from playwright.sync_api import sync_playwright,expect
ROOT=pathlib.Path(__file__).parent;QA=ROOT/'qa';QA.mkdir(exist_ok=True)
checks=[]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,device_scale_factor=1)
    context.add_init_script("""localStorage.setItem('echo-classroom-session-v1','existing-practice-sentinel');window.storageCalls=[];for(const name of ['getItem','setItem','removeItem','clear']){const original=Storage.prototype[name];Storage.prototype[name]=function(...args){window.storageCalls.push(name);return original.apply(this,args);};}""")
    page=context.new_page();errors=[];methods=[];scripts=[]
    page.on('pageerror',lambda _:errors.append('runtime error'))
    page.on('request',lambda r:(methods.append(r.method),scripts.append(r.url) if r.resource_type=='script' else None))
    page.goto('https://group-canvas-echo-classroom.agi144348.workers.dev/',wait_until='networkidle')
    expect(page.locator('body')).to_have_attribute('data-ready','true')
    expect(page.locator('form,input,textarea,select')).to_have_count(0)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    expect(page.locator('.desk')).to_have_count(2)
    expect(page.locator('.reading-note')).to_contain_text('scripted synthetic experiments')
    checks.append('phone-readable documentary with attribution and no participation fields')
    page.screenshot(path=str(QA/'documentary-phone.png'),full_page=True)
    expect(page.locator('#record-number')).to_have_text('RECORD 01 / 96')
    page.locator('#next').tap()
    expect(page.locator('#record-actor')).to_have_text('Scripted teacher fixture')
    expect(page.locator('#teacher-output')).to_contain_text('Correction')
    page.locator('#previous').tap()
    expect(page.locator('#record-number')).to_have_text('RECORD 01 / 96')
    checks.append('saved attempt and teacher-feedback navigation')
    page.get_by_role('button',name='02 · Retention and transfer',exact=True).tap()
    expect(page.locator('#results')).to_contain_text('40/40')
    expect(page.locator('#record-actor')).to_have_text('Frozen Python assessment')
    page.get_by_role('button',name='03 · Notes and Recess',exact=True).tap()
    expect(page.locator('#chapter-subtitle')).to_contain_text('Scripted controller')
    page.get_by_role('button',name='04 · צ tool portfolio',exact=True).tap()
    expect(page.locator('#results')).to_contain_text('Who only')
    checks.append('recorded assessment, controller and tool chapters')
    page.locator('.record-index summary').tap()
    page.locator('#record-list button').last.tap()
    expect(page.locator('#student-output')).to_contain_text('Who is speaking?')
    expect(page.locator('#teacher-output')).to_contain_text('visitor-b')
    expect(page.locator('#record-actor')).to_have_text('Scripted teacher reply')
    page.get_by_text('Inspect the original saved record',exact=True).tap()
    expect(page.locator('#raw')).to_contain_text('teacher-reply')
    assert '021-tsadi-questioning-tool.md' in page.locator('#report').get_attribute('href')
    checks.append('original record/source inspection and retained question with reply')
    assert page.evaluate('window.storageCalls.length')==0
    assert all(m=='GET' for m in methods)
    assert not any(u.endswith('/app.js') or u.endswith('/learner.js') or u.endswith('/tsadi.js') or u.endswith('/priorities.js') for u in scripts)
    assert not errors
    checks.append('GET-only reading, no practice-state access or learner execution, no client errors')
    browser.close()
(QA/'results.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'viewport':'390x844 touch','learningTrialsExecuted':0},indent=2))
print(str(len(checks))+' reading-only phone checks passed; no learning trials executed.')
